const plan = (
  id: string,
  name: string,
  subtitle: string,
  day: number,
  ids: string[],
): Plan => ({
  id,
  name,
  subtitle,
  day,
  minutes: 40,
  exercises: ids.map((exerciseId, i) => ({
    id: `${id}-${i}`,
    exerciseId,
    sets: 2,
    min: catalog[exerciseId].kind === "seconds" ? 20 : 8,
    max: catalog[exerciseId].kind === "seconds" ? 40 : 12,
    rest: 75,
  })),
});
