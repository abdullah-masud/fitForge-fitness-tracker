import type { Exercise, Equipment, Plan, AppData, Muscle, Gear } from "./types";
function exercise(
  id: string,
  name: string,
  primary: Muscle,
  secondary: Muscle[],
  gear: Gear[],
  pose: string,
  steps: string[],
  mistake: string,
  easy: string,
  hard: string,
  options: Partial<Exercise> = {},
): Exercise {
  return {
    id,
    name,
    primary,
    secondary,
    gear,
    pose,
    steps,
    mistake,
    easy,
    hard,
    kind: "reps",
    load: gear.includes("Resistance bands")
      ? "band"
      : gear.includes("Dumbbells")
        ? "dumbbell"
        : gear.includes("Kettlebell")
          ? "kettlebell"
          : "bodyweight",
    count: gear.includes("Dumbbells") ? 2 : 1,
    unilateral: false,
    breath:
      "Exhale during the effort; inhale on the controlled return. Keep breathing.",
    safety:
      "Use a comfortable, controlled range. Stop if you feel sharp pain or persistent discomfort.",
    ...options,
  };
}
